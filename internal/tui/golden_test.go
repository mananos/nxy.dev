package tui

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestTuiGolden draws the screens over the contract of testdata/golden/views and compares them
// with testdata/golden/tui. NXY_WRITE_GOLDEN=1 rewrites them.
func TestTuiGolden(t *testing.T) {
	src, err := NewJSONSource(os.DirFS("../.."), "testdata/golden/views")
	if err != nil {
		t.Fatal(err)
	}
	type tgt struct{ id, key, file string }
	targets := []tgt{
		{"inicio", "", ""}, {"worktrees", "", ""},
		{"feature", "FEAT-A", "FEAT-A"},
		{"agentes", "FEAT-A", "FEAT-A"}, {"agentes", "FEAT-B", "FEAT-B"},
		{"plan", "FEAT-P", "FEAT-P"}, {"plan", "FEAT-Q", "FEAT-Q"},
		{"decision", "", ""},
		{"ingeniero", "FEAT-E", "FEAT-E"},
		{"memoria", "app", "app"}, {"memoria", "global", "global"},
		{"archivo", "api/src/billing/Nota.java", "Nota.java"},
		{"archivo", "api/src/billing/Credito.java", "Credito.java"},
		{"gasto", "", ""}, {"tendencia", "", ""}, {"config", "", ""},
	}
	write := os.Getenv("NXY_WRITE_GOLDEN") == "1"
	dir := filepath.Join("..", "..", "testdata", "golden", "tui")
	if write {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	made := map[string]bool{}
	for _, tg := range targets {
		for _, w := range []int{80, 120, 200} {
			name := tg.id
			if tg.file != "" {
				name += "." + tg.file
			}
			name = fmt.Sprintf("%s.%d.txt", name, w)
			made[name] = true
			feat := ""
			if tg.id == "archivo" {
				feat = "FEAT-P"
			}
			out, err := Render(Options{
				Source: src, Width: w, Dark: true, Plain: true, FileFeature: feat,
				Getenv: func(string) string { return "" }, GOOS: "linux",
			}, tg.id, tg.key)
			if err != nil {
				t.Fatalf("%s: %v", name, err)
			}
			path := filepath.Join(dir, name)
			if write {
				if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
					t.Fatal(err)
				}
				continue
			}
			want, err := os.ReadFile(path)
			if err != nil {
				t.Errorf("%s: %v (NXY_WRITE_GOLDEN=1 writes it)", name, err)
				continue
			}
			if string(want) != out {
				t.Errorf("%s differs (NXY_WRITE_GOLDEN=1 rewrites it)", name)
			}
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if !made[e.Name()] && !strings.HasPrefix(e.Name(), ".") {
			if write {
				_ = os.Remove(filepath.Join(dir, e.Name()))
				continue
			}
			t.Errorf("%s is not generated by the test; remove it", e.Name())
		}
	}
}
