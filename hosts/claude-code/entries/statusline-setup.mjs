#!/usr/bin/env node
// @ts-check
/**
 * `/nxy:statusline` — prints the `statusLine` snippet for ~/.claude/settings.json.
 * With `--apply` it merges the snippet into the user settings (backup first). Claude Code
 * only reads the statusline setting from user/project settings, never from a plugin, so
 * this one step is manual by design.
 *
 * The snippet never points at a versioned plugin copy (`plugins/cache/<mkt>/nxy/<version>/`):
 * that pinned the statusline to whatever version ran `--apply` and silently outlived every
 * update. Instead it runs a small shim in `~/.nxy/statusline.mjs` that picks the newest
 * installed version at runtime, falling back to the root that generated it (a dev checkout).
 */
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { parseArgs } from '../../../core/format.mjs';
import { PLUGIN_ROOT, ensureDir, nxyUserDir } from '../../../core/paths.mjs';
import { claudeUserSettingsPath } from '../settings.mjs';

const fwd = (p) => p.replace(/\\/g, '/');

/**
 * `<plugins>/cache/<marketplace>/<plugin>/<version>` → its `<plugin>` directory, so the shim
 * can look for newer versions next to this one. Any other layout (a git checkout) → null.
 * @param {string} root
 */
export function versionsDirFor(root) {
  if (!/^\d+\.\d+\.\d+/.test(basename(root))) return null;
  const plugin = dirname(root);
  const cache = dirname(dirname(plugin));
  return basename(cache) === 'cache' ? plugin : null;
}

/**
 * Source of the runtime shim. Self-contained: it runs before any plugin code is located.
 * Resolution order: `NXY_STATUSLINE` env → the version Claude Code reports as installed
 * (`<plugins>/installed_plugins.json`, so a rollback keeps hooks and statusline on the same
 * code) → newest `<versionsDir>/<semver>/` that has the script → `fallback` (the root that
 * ran `--apply`). Any failure renders `nxy ?` instead of a blank line.
 * @param {string} root  plugin root at setup time
 */
export function shimSource(root) {
  const fallback = fwd(join(root, 'hosts', 'claude-code', 'statusline.mjs'));
  const versionsDir = versionsDirFor(root);
  // <plugins>/cache/<marketplace>/<plugin>/<version> → <plugins>/installed_plugins.json + "plugin@marketplace"
  const installed = versionsDir ? { file: fwd(join(dirname(dirname(dirname(versionsDir))), 'installed_plugins.json')), key: `${basename(versionsDir)}@${basename(dirname(versionsDir))}` } : null;
  return [
    '// generated by nxy (`/nxy:statusline --apply`) — resolves the installed nxy at runtime',
    "import { existsSync, readFileSync, readdirSync } from 'node:fs';",
    "import { join } from 'node:path';",
    "import { pathToFileURL } from 'node:url';",
    `const versionsDir = ${versionsDir ? JSON.stringify(fwd(versionsDir)) : 'null'};`,
    `const installed = ${installed ? JSON.stringify(installed) : 'null'};`,
    `const fallback = ${JSON.stringify(fallback)};`,
    // Layouts: `hosts/claude-code/` desde 0.2.0, `scripts/metrics/` en 0.1.x — el shim puede
    // resolver una versión instalada anterior al reorden, así que prueba ambos.
    "const scriptIn = (root) => [join(root, 'hosts', 'claude-code', 'statusline.mjs'), join(root, 'scripts', 'metrics', 'statusline.mjs')].find(existsSync) || null;",
    'const semver = (v) => v.split(/[.-]/).map((n) => (Number.isFinite(Number(n)) ? Number(n) : -1));',
    'const cmp = (a, b) => { const x = semver(a), y = semver(b); for (let i = 0; i < 3; i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) - (y[i] ?? 0); return 0; };',
    'let script = process.env.NXY_STATUSLINE || null;',
    'if (!script && installed) {',
    '  try {',
    "    const entries = JSON.parse(readFileSync(installed.file, 'utf8')).plugins?.[installed.key];",
    "    for (const e of Array.isArray(entries) ? entries : []) { const p = e && typeof e.installPath === 'string' ? scriptIn(e.installPath) : null; if (p) { script = p; break; } }",
    '  } catch { /* fall through */ }',
    '}',
    'if (!script && versionsDir) {',
    '  try {',
    "    const candidates = readdirSync(versionsDir).filter((v) => /^\\d+\\.\\d+\\.\\d+/.test(v)).sort(cmp).reverse();",
    '    for (const v of candidates) { const p = scriptIn(join(versionsDir, v)); if (p) { script = p; break; } }',
    '  } catch { /* fall back */ }',
    '}',
    'if (!script || !existsSync(script)) script = fallback;',
    'try {',
    '  const { main } = await import(pathToFileURL(script).href);',
    '  main();',
    '} catch (err) {',
    "  process.stdout.write('nxy ?');",
    "  if (process.env.NXY_DEBUG) process.stderr.write(`[nxy] ${String((err instanceof Error && err.stack) || err)}\\n`);",
    '}',
    '',
  ].join('\n');
}

function run() {
  const { opts } = parseArgs(process.argv.slice(2));
  const shimPath = join(nxyUserDir(), 'statusline.mjs');
  const snippet = { statusLine: { type: 'command', command: `node "${fwd(shimPath)}"`, padding: 0, refreshInterval: 30 } };
  const settingsPath = claudeUserSettingsPath();
  const versionsDir = versionsDirFor(PLUGIN_ROOT);

  if (!opts.apply) {
    console.log('Add this to ~/.claude/settings.json (or run `/nxy:statusline --apply` to merge it for you):');
    console.log(JSON.stringify(snippet, null, 2));
    console.log(`\nThe command runs a shim that ${versionsDir ? `picks the newest version under ${fwd(versionsDir)}` : `points at this checkout (${fwd(PLUGIN_ROOT)})`}; --apply writes it.`);
    if (existsSync(settingsPath)) {
      try {
        const cur = JSON.parse(readFileSync(settingsPath, 'utf8'));
        if (cur.statusLine) console.log(`\nCurrent statusLine: ${JSON.stringify(cur.statusLine)} (will be replaced)`);
      } catch {
        /* ignore */
      }
    }
    console.log('\nRestart Claude Code after the change.');
    return;
  }

  ensureDir(nxyUserDir());
  writeFileSync(shimPath, shimSource(PLUGIN_ROOT));
  console.log(`shim: ${shimPath} (${versionsDir ? `newest version under ${fwd(versionsDir)}` : `this checkout: ${fwd(PLUGIN_ROOT)}`})`);
  let cur = {};
  if (existsSync(settingsPath)) {
    cur = JSON.parse(readFileSync(settingsPath, 'utf8')); // throws on broken JSON: better than overwriting it
    const backup = `${settingsPath}.bak-${Date.now()}`;
    copyFileSync(settingsPath, backup);
    console.log(`backup: ${backup}`);
  }
  writeFileSync(settingsPath, JSON.stringify({ ...cur, ...snippet }, null, 2) + '\n');
  console.log(`statusLine written to ${settingsPath}. Restart Claude Code to see it.`);
}

if (process.argv[1] && /statusline-setup\.mjs$/.test(fwd(process.argv[1]))) run();
